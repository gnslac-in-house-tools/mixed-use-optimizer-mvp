// Recorrido del POT: Uso mixto, una barra de 30 m; en Layers › Site, la sección POT: altura máxima 20 m; el Resumen avisa.
import { createRequire } from 'node:module'
import { mkdirSync } from 'node:fs'
const require = createRequire('C:/dev/mixed-use-optimizer/package.json')
const { chromium } = require('playwright')
const OUT = 'evidence/demo'
mkdirSync(OUT, { recursive: true })
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } })
// los recorridos buscan los textos en inglés (la app arranca en español: src/i18n)
await page.addInitScript(() => localStorage.setItem('gfit-idioma', 'en'))
const errores = []
page.on('pageerror', (e) => errores.push(String(e)))
page.on('console', (m) => { if (m.type() === 'error') errores.push(m.text()) })
const espera = (ms) => page.waitForTimeout(ms)
await page.goto('http://localhost:5180/#/', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: 'New project' }).click()
await page.getByRole('button', { name: 'Uso mixto' }).click()
await page.getByRole('button', { name: 'Create project' }).click()
await espera(1200)
await page.mouse.move(780, 540)
await page.keyboard.press('b')
await espera(300)
await page.mouse.move(980, 390)
await page.keyboard.type('0,0'); await page.keyboard.press('Enter')
await page.mouse.move(1040, 340)
await page.keyboard.type('48.6x16.2'); await page.keyboard.press('Enter')
await espera(800)
await page.getByText('Properties', { exact: true }).first().click()
const alto = page.getByLabel(/^Height/).first()
await alto.fill('30'); await alto.press('Enter')
await espera(800)
await page.mouse.click(600, 800)
await page.keyboard.press('Escape'); await page.keyboard.press('Escape')
await espera(300)
await page.getByText('Properties', { exact: true }).first().click()
await espera(800)
const pot = page.getByRole('region', { name: 'POT' })
console.log('POT visible:', await pot.count())
await page.screenshot({ path: `${OUT}/40-pot.png` })
const h = pot.getByLabel(/^Altura máxima/)
await h.fill('20'); await h.press('Enter')
await espera(1500)
console.log('aviso:', (await page.locator('body').innerText()).match(/POT: [^\n]*/g))
await page.screenshot({ path: `${OUT}/41-pot-aviso.png` })
console.log(JSON.stringify({ errores }, null, 2))
await browser.close()
